#!/usr/bin/env node
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const src = fs.readFileSync(path.join(__dirname,"../pages-preview/app.js"),"utf8");
const start = src.indexOf("function buildCumulativeMonthlyHours(");
const end = src.indexOf("\nfunction renderCumulativeComparison(",start);
assert(start >= 0 && end > start,"Cumulative helper missing");
const build = vm.runInNewContext(src.slice(start,end)+"\nbuildCumulativeMonthlyHours;");
const norm = x => JSON.parse(JSON.stringify(x));
const city = rows => ({monthly:rows.map(([month,avg_daily_alert_hours,extra])=>({month,avg_daily_alert_hours,...extra}))});
const input = {a:city([["2024-01",1],["2024-02",2],["2024-03",0]]),b:city([["2024-01",2],["2024-02",0],["2024-03",1]])};
let x = norm(build(["a","b"],input,"2024-01-01","2024-03-31"));
assert.deepEqual(x.months,["2024-01","2024-02","2024-03"]);
assert.deepEqual(x.totals,[[31,89,89],[62,62,93]],"Leap Feb=29 days and zero month");
assert.deepEqual(x.additions,[[31,58,0],[62,0,31]]);
assert.equal(x.blockedBy,null);
x=norm(build(["a","b"],input,"2024-02-01","2024-02-29"));
assert.deepEqual(x.months,["2024-02"]);
assert.deepEqual(x.totals,[[58],[0]],"Range resets to zero");
assert.deepEqual(norm(build(["a","b"],input,"2024-02-02","2024-02-29")).months,[],"Partial starting month");
assert.deepEqual(norm(build(["a","b"],input,"2024-02-01","2024-02-28")).months,[],"Partial ending month");
x=norm(build(["a","b"],{a:city([["2024-01",1],["2024-03",1]]),b:city([["2024-01",1],["2024-02",1],["2024-03",1]])},"2024-01-01","2024-03-31"));
assert.deepEqual(x.months,["2024-01"],"No bridging a gap");
assert.equal(x.blockedBy,"2024-03");
x=norm(build(["a","b"],{a:city([["2024-01",1],["2024-02",null]]),b:city([["2024-01",1],["2024-02",1]])},"2024-01-01","2024-02-29"));
assert.deepEqual(x.months,["2024-01"],"Null is not zero");
assert.equal(x.blockedBy,"2024-02");
x=norm(build(["a","b"],{a:city([["2024-01",1],["2024-02",1,{is_partial_period:true}]]),b:city([["2024-01",1],["2024-02",1]])},"2024-01-01","2024-02-29"));
assert.deepEqual(x.months,["2024-01"],"No partial month");
assert.equal(x.blockedBy,"2024-02");
x=norm(build(["a","b"],{a:{monthly:[{month:"2024-01",avg_daily_alert_hours:1,total_alert_duration_hours:12.5}]},b:city([["2024-01",1]])},"2024-01-01","2024-01-31"));
assert.deepEqual(x.totals,[[12.5],[31]],"Direct monthly total wins");
assert.equal((src.match(/renderCumulativeComparison\(keys\);/g)||[]).length,1,"Render hooked exactly once");
assert(src.includes('compareCumulativeHoursChart: { slug: "compare-cumulative-hours"'),"CSV export configured");
console.log("PASS: cumulative monthly hours, leap year, range reset, missing/partial guard and export hook");
