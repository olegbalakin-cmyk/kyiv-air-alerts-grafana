#!/usr/bin/env node
"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.join(__dirname,"..");
const app=fs.readFileSync(path.join(root,"pages-preview/app.js"),"utf8");
const html=fs.readFileSync(path.join(root,"pages-preview/index.html"),"utf8");
const css=fs.readFileSync(path.join(root,"pages-preview/styles.css"),"utf8");
const a=app.indexOf("function buildBlockShareUrl("),b=app.indexOf("\nfunction shareLinkIcon(",a);
assert(a>=0&&b>a,"Stable permalink helper exists");
const helpers=vm.runInNewContext(app.slice(a,b)+"\n({buildBlockShareUrl,findSharedBlock})",{URL});
const base="https://olegbalakin-cmyk.github.io/kyiv-air-alerts-grafana/?city=kyiv&lang=uk&a=kyiv&b=kharkiv&daypartmode=daynight&burdenyear=all";
const url=new URL(helpers.buildBlockShareUrl(base,"block-compareCumulativeHoursChart"));
assert.equal(url.hash,"#block-compareCumulativeHoursChart");
for(const [key,val] of [["city","kyiv"],["lang","uk"],["a","kyiv"],["b","kharkiv"],["daypartmode","daynight"],["burdenyear","all"]])assert.equal(url.searchParams.get(key),val);
assert.equal(new URL(helpers.buildBlockShareUrl(base+"#old","timeOfDaySection")).hash,"#timeOfDaySection");
const mock={getElementById:id=>id==="block-cityIntensityChart"?{classList:{contains:x=>x==="shareable-block"},closest:()=>null}:null};
assert(helpers.findSharedBlock("#block-cityIntensityChart",mock));
assert.equal(helpers.findSharedBlock("#bad%3Ax",mock),null);
assert.equal(helpers.findSharedBlock("#missing",mock),null);
assert.equal(helpers.findSharedBlock("#block-cityIntensityChart",{getElementById:()=>({classList:{contains:()=>true},closest:()=>({})})}),null);
assert(app.includes('location.hash || ""'),"Hash retained when filter changes");
assert(app.includes("setupShareButtons();"));
assert(app.includes("if (!restoreSharedBlock()) maybeStartIntroTour();"));
for(const t of [".chart-card",".comparison-section[id]",".kpi-card"])assert(app.includes('document.querySelectorAll("'+t+'")'));
assert(app.includes('block-allCitiesTable')&&app.includes('block-kpis'));
assert(app.includes('navigator.share')&&app.includes('navigator.clipboard'));
assert(css.includes(".share-action-button")&&css.includes(".shareable-block:target"));
assert(html.includes("20261013-share1"),"New app/css cache versions");
console.log("PASS: shareable chart, section, KPI, table anchors and parameter-preserving links");
